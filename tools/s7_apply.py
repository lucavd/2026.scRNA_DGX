#!/usr/bin/env python3
"""S7 edits to the Markdown sources before the LaTeX conversion (ledger R0719, R0721, R0734).

Every edit is an exact replacement with a declared number of occurrences; the
script stops without writing if any count differs. It then regenerates
figures/LEGENDS.md from the current captions (S5 doubt) and appends one row
per ledger entry to manuscript/revisione_n2/piano/IMPL_diario.csv.

Usage: python3 -B tools/s7_apply.py [--dry-run]
"""
import argparse, csv, hashlib, json, os, re, sys, datetime

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN = os.path.join(REPO, "manuscript/full_paper_LNBI.md")
SUP = os.path.join(REPO, "manuscript/supplementary_LNBI.md")
DIARY = os.path.join(REPO, "manuscript/revisione_n2/piano/IMPL_diario.csv")
TODAY = "2026-11-05"

DISC_OLD = "# Conflict of Interest\n\nThe authors declare no conflict of interest.\n\n"
DISC_NEW = ("# Disclosure of Interests\n\nThe authors have no competing interests to declare that are "
            "relevant to the content of this article.\n\n")


def md5s(s):
    return hashlib.md5(s.encode("utf-8")).hexdigest()


def replace(text, old, new, n, what, log, regex=False):
    k = len(re.findall(old, text, flags=re.M)) if regex else text.count(old)
    if k != n:
        sys.exit("%s: expected %d occurrences, found %d" % (what, n, k))
    text = re.sub(old, new, text, flags=re.M) if regex else text.replace(old, new)
    log.append({"edit": what, "occurrences": k})
    return text


def reorder_back_matter(text, log):
    """Conclusions, Availability, Acknowledgements, Funding, Disclosure of Interests, References."""
    def grab(name):
        m = re.search(r"(?ms)^# %s\s*\n.*?(?=^# )" % re.escape(name), text)
        if not m:
            sys.exit("section not found: " + name)
        return m
    names = ["Conflict of Interest", "Acknowledgements", "Funding", "Availability of Data and Software Code"]
    blocks = {n: grab(n).group(0) for n in names}
    start = min(grab(n).start() for n in names)
    end = max(grab(n).end() for n in names)
    if not text[end:].startswith("# References"):
        sys.exit("back matter not followed by References")
    if blocks["Conflict of Interest"] != DISC_OLD:
        sys.exit("Conflict of Interest text differs from the ledger value_old (R0734)")
    new = (blocks["Availability of Data and Software Code"] + blocks["Acknowledgements"] +
           blocks["Funding"] + DISC_NEW)
    log.append({"edit": "R0734 back matter reordered; Conflict of Interest -> Disclosure of Interests",
                "occurrences": 1})
    return text[:start] + new + text[end:]


def legends(main, sup):
    """figures/LEGENDS.md from the current captions, with the file of each figure."""
    out = ["# Figure legends (generated)", "",
           "Generated by `tools/s7_apply.py` from the captions of `manuscript/full_paper_LNBI.md` and "
           "`manuscript/supplementary_LNBI.md` (step S7, %s). The chapter and the supplement include the "
           "vector PDF next to each PNG; the LaTeX source copies it as `figN.pdf` / `figSN.pdf` "
           "(`tools/s7_md2lncs.py`). Do not edit by hand." % TODAY, "",
           "| number | document | generated file | LaTeX / METEOR file |", "|---|---|---|---|"]
    caps = []
    for doc, text in (("chapter", main), ("supplement", sup)):
        for cap, path in re.findall(r"!\[(.*?)\]\(([^)]+\.png)\)", text, flags=re.S):
            num = re.match(r"\*\*Figure (S?\d+)\.\*\*", cap).group(1)
            pdf = os.path.basename(os.path.splitext(path)[0] + ".pdf")
            out.append("| %s | %s | `figures/%s` | `fig%s.pdf` |" % (num, doc, pdf, num))
            caps.append((num, cap))
    out.append("")
    for num, cap in caps:
        out += ["## Figure %s" % num, "", re.sub(r"^\*\*Figure S?\d+\.\*\*\s*", "", cap), ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    m0, s0 = open(MAIN, encoding="utf-8").read(), open(SUP, encoding="utf-8").read()
    log = []
    m = replace(m0, r"^(\| CPU \(Scanpy\) \|.*)\| --- \|$", r"\1| n.a. |", 5,
                "R0721 chapter Table 1: Peak VRAM of the five CPU rows", log, regex=True)
    m = reorder_back_matter(m, log)
    s = replace(s0, "| 1 | Data loading | --- |", "| 1 | Data loading | n.a. |", 1,
                "R0721 Table S1 step 1 key parameters", log)
    s = replace(s, "| 12.0M | --- | --- | --- |", "| 12.0M | n.a. | n.a. | n.a. |", 1,
                "R0721 Table S4 row 12.0M", log)
    s = replace(s, "| 13.7M | --- | --- | --- |", "| 13.7M | n.a. | n.a. | n.a. |", 1,
                "R0721 Table S4 row 13.7M", log)
    s = replace(s, "| PCA loading |rho| |", "| PCA loading \\|rho\\| |", 1,
                "R0719 Table S2 row PCA loading (escaped bars)", log)
    for name, t in (("chapter", m), ("supplement", s)):
        rest = re.findall(r"\|\s*---\s*\|", "\n".join(l for l in t.split("\n") if not re.match(r"^\|[-|: ]*\|$", l)))
        if rest:
            sys.exit("%s: cells '---' left: %d" % (name, len(rest)))
        if "\u2013" in t or "\u2014" in t:
            sys.exit(name + ": U+2013/U+2014 present")
    leg = legends(m, s)
    rec = {"at": datetime.datetime.now().astimezone().replace(microsecond=0).isoformat(), "edits": log,
           "main_md5": [md5s(m0), md5s(m)], "sup_md5": [md5s(s0), md5s(s)], "legends_md5": md5s(leg)}
    print(json.dumps(rec, indent=1, ensure_ascii=False))
    if a.dry_run:
        return
    open(MAIN, "w", encoding="utf-8").write(m)
    open(SUP, "w", encoding="utf-8").write(s)
    open(os.path.join(REPO, "figures/LEGENDS.md"), "w", encoding="utf-8").write(leg)
    rows = [
        ["R0719", "L1", "fatto", "PCA loading \\|rho\\| (barre protette) in Table S2", "", "supplementary_LNBI.md", "supplemento", TODAY,
         "Dopo il taglio di S6 la riga sta nel supplemento (Table S2)."],
        ["R0721", "L2", "fatto", "n.a. in 12 celle (5 in Table 1 del capitolo, 1 in Table S1, 6 in Table S4)", "", "full_paper_LNBI.md; supplementary_LNBI.md", "capitolo e supplemento", TODAY,
         "Dopo S6 le celle erano 12, come nel piano, in tabelle rinumerate."],
        ["R0734", "L2", "fatto", "Disclosure of Interests con la formula Springer; Availability prima dei ringraziamenti; Acknowledgements, Funding e Disclosure nell'ambiente credits del .tex", "", "manuscript/lncs_latex/llncs.cls (credits, \\ackname, \\discintname)", "capitolo, fine", TODAY,
         ".tex rigenerato da tools/s7_md2lncs.py; ricevuta results_v2/S7/build/chapter/receipt.json."],
    ]
    with open(DIARY, "a", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\r\n")
        for r in rows:
            w.writerow(r)
    json.dump(rec, open(os.path.join(REPO, "results_v2/S7/s7_apply.json"), "w"), indent=1, ensure_ascii=False)


if __name__ == "__main__":
    main()
